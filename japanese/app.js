const state = {
  language: 'vi',
  topics: [],
  allQuestions: [],
  selectedTopicId: null,
  mode: null,
  questionLimit: null,
  questions: [],
  currentIndex: 0,
  responses: new Map(),
  timerId: null,
  deadline: null,
  timeRemaining: 0,
  sessionDuration: 0,
  startedAt: null,
  timeSpent: 0,
  currentScreen: 'setup-screen',
  studyQuery: '',
  studyRenderTimer: null,
};

document.addEventListener('DOMContentLoaded', initializeApp);

function initializeApp() {
  if (typeof JAPANESE_TOPICS === 'undefined' || typeof JAPANESE_QUESTIONS === 'undefined') {
    const banner = document.getElementById('data-error');
    banner.hidden = false;
    banner.textContent = I18N.vi.dataError;
    document.getElementById('start-button').disabled = true;
    return;
  }

  state.topics = JAPANESE_TOPICS;
  state.allQuestions = JAPANESE_QUESTIONS;
  bindEventListeners();
  renderSetup();
  applyTranslations();
  showScreen('setup-screen', false);
}

function bindEventListeners() {
  document.getElementById('lang-vi').addEventListener('click', () => setLanguage('vi'));
  document.getElementById('lang-ja').addEventListener('click', () => setLanguage('ja'));

  document.querySelectorAll('[data-mode]').forEach((button) => {
    button.addEventListener('click', () => selectMode(button.dataset.mode));
  });

  document.getElementById('start-button').addEventListener('click', startSession);
  document.getElementById('previous-button').addEventListener('click', previousQuestion);
  document.getElementById('submit-answer-button').addEventListener('click', submitPracticeAnswer);
  document.getElementById('next-button').addEventListener('click', nextQuestion);
  document.getElementById('finish-exam-button').addEventListener('click', requestFinishExam);
  document.getElementById('exit-quiz-button').addEventListener('click', requestExitSession);
  document.getElementById('exit-study-button').addEventListener('click', () => showScreen('setup-screen'));
  document.getElementById('retry-button').addEventListener('click', startSession);
  document.getElementById('back-setup-button').addEventListener('click', () => showScreen('setup-screen'));
  document.getElementById('open-navigator-button').addEventListener('click', openNavigator);
  document.getElementById('close-navigator-button').addEventListener('click', () => closeNavigator());
  document.getElementById('navigator-overlay').addEventListener('click', () => closeNavigator());
  document.getElementById('jump-form').addEventListener('submit', (event) => {
    event.preventDefault();
    const input = document.getElementById('jump-input');
    const number = Number(input.value);
    if (Number.isInteger(number) && number >= 1 && number <= state.questions.length) {
      goToQuestion(number - 1);
      input.value = '';
    } else {
      input.focus();
    }
  });

  document.getElementById('study-search').addEventListener('input', (event) => {
    state.studyQuery = event.target.value;
    clearTimeout(state.studyRenderTimer);
    state.studyRenderTimer = setTimeout(renderStudyList, 120);
  });

  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape' && document.getElementById('question-navigator').classList.contains('open')) {
      closeNavigator();
      return;
    }
    if (state.currentScreen !== 'quiz-screen' || event.altKey || event.ctrlKey || event.metaKey) return;
    const optionIndex = Number(event.key) - 1;
    if (optionIndex >= 0 && optionIndex <= 8) {
      const response = currentResponse();
      const optionId = response?.optionOrder[optionIndex];
      if (optionId) selectOption(optionId);
    }
  });
}

function t(key, replacements = {}) {
  let value = I18N[state.language][key] ?? I18N.vi[key] ?? key;
  Object.entries(replacements).forEach(([name, replacement]) => {
    value = value.replaceAll(`{${name}}`, replacement);
  });
  return value;
}

function localized(field) {
  if (!field) return '';
  return field[state.language] || field.vi || field.ja || '';
}

function formatNumber(value) {
  return new Intl.NumberFormat(state.language === 'ja' ? 'ja-JP' : 'vi-VN').format(value);
}

function setLanguage(language) {
  if (state.language === language) return;
  state.language = language;
  document.documentElement.lang = language;
  applyTranslations();
  renderSetup();

  if (state.currentScreen === 'quiz-screen') renderQuestion();
  if (state.currentScreen === 'study-screen') {
    updateStudyHeader();
    renderStudyList();
  }
  if (state.currentScreen === 'results-screen') renderResults();
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });

  ['vi', 'ja'].forEach((language) => {
    const button = document.getElementById(`lang-${language}`);
    const active = language === state.language;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
  document.getElementById('hero-question-count').textContent = formatNumber(state.allQuestions.length || 1192);
}

function renderSetup() {
  renderTopicCards();
  renderMaterialCards();
  updateSelectionPanel();
}

function quizTopics() {
  return state.topics.filter(({ type }) => type === 'quiz');
}

function materialTopics() {
  return state.topics.filter(({ type }) => type === 'material');
}

function allTopic() {
  return {
    id: 'all',
    type: 'quiz',
    title: { vi: I18N.vi.allQuestions, ja: I18N.ja.allQuestions },
    description: { vi: I18N.vi.allDescription, ja: I18N.ja.allDescription },
    count: state.allQuestions.length,
  };
}

function selectedTopic() {
  if (state.selectedTopicId === 'all') return allTopic();
  return quizTopics().find(({ id }) => id === state.selectedTopicId) || null;
}

function selectedQuestionPool() {
  if (state.selectedTopicId === 'all') return [...state.allQuestions];
  return state.allQuestions.filter(({ topicId }) => topicId === state.selectedTopicId);
}

function renderTopicCards() {
  const grid = document.getElementById('quiz-topic-grid');
  const topics = [allTopic(), ...quizTopics()];
  const fragment = document.createDocumentFragment();

  topics.forEach((topic) => {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = `topic-card${topic.id === 'all' ? ' all-topic' : ''}`;
    button.classList.toggle('selected', topic.id === state.selectedTopicId);
    button.setAttribute('aria-pressed', String(topic.id === state.selectedTopicId));
    button.addEventListener('click', () => selectTopic(topic.id));

    const index = document.createElement('span');
    index.className = 'topic-index';
    index.textContent = topic.id === 'all' ? '全' : topic.id;

    const copy = document.createElement('span');
    copy.className = 'topic-card-copy';
    const title = document.createElement('h3');
    title.textContent = localized(topic.title);
    const description = document.createElement('span');
    description.className = 'topic-description';
    description.textContent = localized(topic.description);
    const count = document.createElement('span');
    count.className = 'topic-count';
    count.textContent = `${formatNumber(topic.count)} ${t('questions')}`;

    copy.append(title, description, count);
    button.append(index, copy);
    fragment.append(button);
  });

  grid.replaceChildren(fragment);
}

function renderMaterialCards() {
  const grid = document.getElementById('material-grid');
  const fragment = document.createDocumentFragment();

  materialTopics().forEach((topic) => {
    const link = document.createElement('a');
    link.className = 'material-card';
    link.href = topic.href;

    const symbol = document.createElement('span');
    symbol.className = 'material-symbol';
    symbol.setAttribute('aria-hidden', 'true');
    symbol.textContent = topic.id === '09' ? '史' : '文';

    const copy = document.createElement('span');
    const title = document.createElement('h3');
    title.textContent = localized(topic.title);
    const description = document.createElement('p');
    description.textContent = localized(topic.description);
    copy.append(title, description);

    const arrow = document.createElement('span');
    arrow.className = 'material-arrow';
    arrow.setAttribute('aria-label', t('openMaterial'));
    arrow.textContent = '→';

    link.append(symbol, copy, arrow);
    fragment.append(link);
  });

  grid.replaceChildren(fragment);
}

function selectTopic(topicId) {
  state.selectedTopicId = topicId;
  state.mode = null;
  state.questionLimit = null;
  renderSetup();
  document.getElementById('mode-section').scrollIntoView({ behavior: 'smooth', block: 'center' });
}

function updateSelectionPanel() {
  const topic = selectedTopic();
  const section = document.getElementById('mode-section');
  const modeButtons = document.querySelectorAll('[data-mode]');
  const startButton = document.getElementById('start-button');

  section.classList.toggle('disabled', !topic);
  section.setAttribute('aria-disabled', String(!topic));
  modeButtons.forEach((button) => {
    button.disabled = !topic;
    button.classList.toggle('selected', button.dataset.mode === state.mode);
    button.setAttribute('aria-pressed', String(button.dataset.mode === state.mode));
  });

  document.getElementById('selection-summary').textContent = topic
    ? t('selectedSummary', { title: localized(topic.title), count: formatNumber(topic.count) })
    : t('selectTopicFirst');

  if (state.mode && state.mode !== 'study') {
    renderCountOptions();
  } else {
    document.getElementById('count-picker').hidden = true;
  }

  startButton.disabled = !topic || !state.mode || (state.mode !== 'study' && state.questionLimit === null);
}

function selectMode(mode) {
  if (!selectedTopic()) return;
  state.mode = mode;
  state.questionLimit = null;

  if (mode === 'study') {
    state.questionLimit = 'all';
  } else {
    const available = allowedCounts(mode, selectedQuestionPool().length);
    state.questionLimit = available[0] ?? null;
  }
  updateSelectionPanel();
}

function allowedCounts(mode, available) {
  const candidates = mode === 'practice' ? [10, 25, 50] : [25, 50, 100];
  const allowed = candidates.filter((count) => count <= available);
  if (mode === 'practice') allowed.push('all');
  return allowed;
}

function renderCountOptions() {
  const picker = document.getElementById('count-picker');
  const container = document.getElementById('count-options');
  const available = selectedQuestionPool().length;
  const values = allowedCounts(state.mode, available);
  const fragment = document.createDocumentFragment();

  values.forEach((value) => {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'count-button';
    button.classList.toggle('selected', value === state.questionLimit);
    button.setAttribute('aria-pressed', String(value === state.questionLimit));
    button.textContent = value === 'all' ? `${t('all')} (${formatNumber(available)})` : formatNumber(value);
    button.addEventListener('click', () => {
      state.questionLimit = value;
      renderCountOptions();
      document.getElementById('start-button').disabled = false;
    });
    fragment.append(button);
  });

  container.replaceChildren(fragment);
  picker.hidden = false;
}

function shuffle(items) {
  const shuffled = [...items];
  for (let index = shuffled.length - 1; index > 0; index -= 1) {
    const randomIndex = Math.floor(Math.random() * (index + 1));
    [shuffled[index], shuffled[randomIndex]] = [shuffled[randomIndex], shuffled[index]];
  }
  return shuffled;
}

function resetActiveSession() {
  clearInterval(state.timerId);
  closeNavigator(false);
  state.timerId = null;
  state.deadline = null;
  state.questions = [];
  state.currentIndex = 0;
  state.responses = new Map();
  state.timeRemaining = 0;
  state.sessionDuration = 0;
  state.startedAt = null;
  state.timeSpent = 0;
  state.studyQuery = '';
  document.getElementById('study-search').value = '';
  document.getElementById('question-navigator-grid').replaceChildren();
  document.getElementById('navigator-progress').textContent = '0/0';
}

function startSession() {
  if (!selectedTopic() || !state.mode) return;
  const pool = selectedQuestionPool();
  resetActiveSession();

  if (state.mode === 'study') {
    state.questions = pool;
    updateStudyHeader();
    renderStudyList();
    showScreen('study-screen');
    return;
  }

  const shuffledPool = shuffle(pool);
  state.questions = state.questionLimit === 'all'
    ? shuffledPool
    : shuffledPool.slice(0, Number(state.questionLimit));
  state.startedAt = Date.now();
  state.responses = new Map(state.questions.map((question) => [
    question.id,
    {
      selectedOptionId: null,
      isAnswered: false,
      isCorrect: false,
      optionOrder: shuffle(question.options.map(({ id }) => id)),
    },
  ]));
  renderNavigatorGrid();

  if (state.mode === 'exam') {
    state.sessionDuration = state.questions.length * 60;
    state.timeRemaining = state.sessionDuration;
    state.deadline = Date.now() + state.sessionDuration * 1000;
    startTimer();
  }

  showScreen('quiz-screen');
  renderQuestion();
}

function currentQuestion() {
  return state.questions[state.currentIndex] || null;
}

function currentResponse() {
  const question = currentQuestion();
  return question ? state.responses.get(question.id) : null;
}

function selectOption(optionId) {
  const question = currentQuestion();
  const response = currentResponse();
  if (!question || !response) return;
  if (state.mode === 'practice' && response.isAnswered) return;

  response.selectedOptionId = optionId;
  if (state.mode === 'exam') response.isAnswered = true;
  renderQuestion();
}

function submitPracticeAnswer() {
  const question = currentQuestion();
  const response = currentResponse();
  if (!question || !response?.selectedOptionId || response.isAnswered) return;

  response.isAnswered = true;
  response.isCorrect = response.selectedOptionId === question.correctOptionId;
  renderQuestion();
}

function previousQuestion() {
  if (state.currentIndex === 0) return;
  state.currentIndex -= 1;
  renderQuestion();
}

function nextQuestion() {
  if (state.currentIndex < state.questions.length - 1) {
    state.currentIndex += 1;
    renderQuestion();
    return;
  }

  if (state.mode === 'exam') {
    requestFinishExam();
  } else {
    finishSession();
  }
}

function requestFinishExam() {
  if (window.confirm(t('finishConfirm'))) finishSession();
}

function requestExitSession() {
  if (window.confirm(t('exitConfirm'))) {
    resetActiveSession();
    showScreen('setup-screen');
  }
}

function renderQuestion() {
  const question = currentQuestion();
  const response = currentResponse();
  if (!question || !response) return;

  const topic = selectedTopic();
  document.getElementById('quiz-topic-label').textContent = localized(topic.title);
  document.getElementById('progress-label').textContent = t('questionProgress', {
    current: formatNumber(state.currentIndex + 1),
    total: formatNumber(state.questions.length),
  });
  const answeredCount = [...state.responses.values()].filter(({ isAnswered }) => isAnswered).length;
  document.getElementById('answered-label').textContent = t('answeredProgress', { count: formatNumber(answeredCount) });
  document.getElementById('progress-fill').style.width = `${((state.currentIndex + 1) / state.questions.length) * 100}%`;
  document.getElementById('question-source').textContent = question.source
    ? `${question.id} • ${t('source')}: ${question.source}`
    : question.id;
  document.getElementById('question-text').textContent = localized(question.question);

  const optionsContainer = document.getElementById('options-container');
  const fragment = document.createDocumentFragment();

  response.optionOrder.forEach((optionId, index) => {
    const option = question.options.find(({ id }) => id === optionId);
    if (!option) return;
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'option-button';
    button.dataset.optionId = option.id;
    button.setAttribute('aria-pressed', String(response.selectedOptionId === option.id));
    button.addEventListener('click', () => selectOption(option.id));

    if (response.selectedOptionId === option.id) button.classList.add('selected');
    if (state.mode === 'practice' && response.isAnswered) {
      button.disabled = true;
      if (option.id === question.correctOptionId) button.classList.add('correct');
      if (response.selectedOptionId === option.id && !response.isCorrect) button.classList.add('incorrect');
    }

    const key = document.createElement('span');
    key.className = 'option-key';
    key.textContent = String(index + 1);
    const text = document.createElement('span');
    text.className = 'option-text';
    text.textContent = localized(option);
    button.append(key, text);
    fragment.append(button);
  });
  optionsContainer.replaceChildren(fragment);

  const explanationPanel = document.getElementById('explanation-panel');
  const showExplanation = state.mode === 'practice' && response.isAnswered;
  explanationPanel.hidden = !showExplanation;
  if (showExplanation) {
    document.getElementById('explanation-text').textContent = localized(question.explanation);
  }

  document.getElementById('previous-button').disabled = state.currentIndex === 0;
  const submitButton = document.getElementById('submit-answer-button');
  const nextButton = document.getElementById('next-button');
  const finishButton = document.getElementById('finish-exam-button');
  const timerBox = document.getElementById('timer-box');

  timerBox.hidden = state.mode !== 'exam';
  finishButton.hidden = state.mode !== 'exam';

  if (state.mode === 'practice') {
    submitButton.hidden = response.isAnswered;
    submitButton.disabled = !response.selectedOptionId;
    nextButton.hidden = !response.isAnswered;
    nextButton.textContent = state.currentIndex === state.questions.length - 1 ? t('finishPractice') : t('next');
  } else {
    submitButton.hidden = true;
    nextButton.hidden = false;
    nextButton.textContent = state.currentIndex === state.questions.length - 1 ? t('submitExam') : t('next');
  }
  updateNavigatorState();
}

function renderNavigatorGrid() {
  const grid = document.getElementById('question-navigator-grid');
  const input = document.getElementById('jump-input');
  const fragment = document.createDocumentFragment();

  input.max = String(state.questions.length);
  state.questions.forEach((question, index) => {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'navigator-question';
    button.dataset.questionIndex = String(index);
    button.textContent = String(index + 1);
    button.title = question.id;
    button.addEventListener('click', () => goToQuestion(index));
    fragment.append(button);
  });
  grid.replaceChildren(fragment);
  updateNavigatorState();
}

function updateNavigatorState() {
  const buttons = document.getElementById('question-navigator-grid').children;
  if (buttons.length !== state.questions.length) return;

  let answered = 0;
  state.questions.forEach((question, index) => {
    const response = state.responses.get(question.id);
    const button = buttons[index];
    button.className = 'navigator-question';
    button.classList.toggle('current', index === state.currentIndex);
    button.setAttribute('aria-current', index === state.currentIndex ? 'step' : 'false');
    button.setAttribute('aria-label', t('questionAriaLabel', {
      number: formatNumber(index + 1),
      id: question.id,
    }));

    if (response?.isAnswered) {
      answered += 1;
      if (state.mode === 'practice') {
        button.classList.add(response.isCorrect ? 'correct' : 'incorrect');
      } else {
        button.classList.add('answered');
      }
    }
    if (index === state.currentIndex) button.classList.add('current');
  });

  document.getElementById('navigator-progress').textContent = `${formatNumber(state.currentIndex + 1)}/${formatNumber(state.questions.length)}`;
  document.getElementById('navigator-summary').textContent = t('navigatorSummary', {
    answered: formatNumber(answered),
    total: formatNumber(state.questions.length),
  });
}

function openNavigator() {
  if (state.currentScreen !== 'quiz-screen') return;
  const navigator = document.getElementById('question-navigator');
  const overlay = document.getElementById('navigator-overlay');
  navigator.classList.add('open');
  navigator.setAttribute('aria-hidden', 'false');
  overlay.classList.add('open');
  overlay.setAttribute('aria-hidden', 'false');
  document.body.classList.add('navigator-open');
  updateNavigatorState();
  requestAnimationFrame(() => {
    const current = document.querySelector('.navigator-question.current');
    current?.scrollIntoView({ block: 'center' });
    document.getElementById('close-navigator-button').focus();
  });
}

function closeNavigator(restoreFocus = true) {
  const navigator = document.getElementById('question-navigator');
  const overlay = document.getElementById('navigator-overlay');
  if (!navigator || !overlay) return;
  const wasOpen = navigator.classList.contains('open');
  navigator.classList.remove('open');
  navigator.setAttribute('aria-hidden', 'true');
  overlay.classList.remove('open');
  overlay.setAttribute('aria-hidden', 'true');
  document.body.classList.remove('navigator-open');
  if (restoreFocus && wasOpen) document.getElementById('open-navigator-button').focus();
}

function goToQuestion(index) {
  if (!Number.isInteger(index) || index < 0 || index >= state.questions.length) return;
  state.currentIndex = index;
  renderQuestion();
  closeNavigator();
}

function startTimer() {
  clearInterval(state.timerId);
  updateTimer();
  state.timerId = setInterval(updateTimer, 1000);
}

function updateTimer() {
  if (!state.deadline) return;
  state.timeRemaining = Math.max(0, Math.ceil((state.deadline - Date.now()) / 1000));
  document.getElementById('timer-value').textContent = formatDuration(state.timeRemaining);

  if (state.timeRemaining === 0) {
    clearInterval(state.timerId);
    state.timerId = null;
    window.alert(t('timeUp'));
    finishSession();
  }
}

function finishSession() {
  clearInterval(state.timerId);
  closeNavigator(false);
  state.timerId = null;

  state.responses.forEach((response, questionId) => {
    const question = state.questions.find(({ id }) => id === questionId);
    response.isCorrect = Boolean(response.selectedOptionId && response.selectedOptionId === question.correctOptionId);
  });

  state.timeSpent = state.mode === 'exam'
    ? Math.max(0, state.sessionDuration - state.timeRemaining)
    : Math.max(0, Math.round((Date.now() - state.startedAt) / 1000));
  showScreen('results-screen');
  renderResults();
}

function renderResults() {
  const responses = [...state.responses.values()];
  const correct = responses.filter(({ isCorrect }) => isCorrect).length;
  const unanswered = responses.filter(({ selectedOptionId }) => !selectedOptionId).length;
  const incorrect = responses.length - correct - unanswered;
  const percent = responses.length ? Math.round((correct / responses.length) * 100) : 0;

  document.getElementById('score-percent').textContent = `${percent}%`;
  document.getElementById('score-fraction').textContent = `${formatNumber(correct)} / ${formatNumber(responses.length)}`;
  document.getElementById('correct-count').textContent = formatNumber(correct);
  document.getElementById('incorrect-count').textContent = formatNumber(incorrect);
  document.getElementById('unanswered-count').textContent = formatNumber(unanswered);
  document.getElementById('time-spent').textContent = formatDuration(state.timeSpent);
  renderReviewList();
}

function renderReviewList() {
  const container = document.getElementById('review-list');
  const incorrectQuestions = state.questions.filter((question) => !state.responses.get(question.id).isCorrect);

  if (incorrectQuestions.length === 0) {
    const message = document.createElement('p');
    message.className = 'empty-message';
    message.textContent = t('noMistakes');
    container.replaceChildren(message);
    return;
  }

  const fragment = document.createDocumentFragment();
  incorrectQuestions.forEach((question) => {
    const response = state.responses.get(question.id);
    const selectedOption = question.options.find(({ id }) => id === response.selectedOptionId);
    const correctOption = question.options.find(({ id }) => id === question.correctOptionId);

    const card = document.createElement('article');
    card.className = 'review-card';
    const meta = document.createElement('div');
    meta.className = 'review-meta';
    meta.append(makeTextSpan(question.id), makeTextSpan(question.source || ''));
    const heading = document.createElement('h3');
    heading.textContent = localized(question.question);
    const answers = document.createElement('div');
    answers.className = 'answer-summary';
    answers.append(
      makeAnswerLine(`${t('yourAnswer')}: ${selectedOption ? localized(selectedOption) : t('noAnswer')}`, 'user-wrong'),
      makeAnswerLine(`${t('correctAnswer')}: ${localized(correctOption)}`, 'correct-answer'),
    );
    card.append(meta, heading, answers);
    fragment.append(card);
  });
  container.replaceChildren(fragment);
}

function makeTextSpan(text) {
  const span = document.createElement('span');
  span.textContent = text;
  return span;
}

function makeAnswerLine(text, className) {
  const line = document.createElement('div');
  line.className = `answer-line ${className}`;
  line.textContent = text;
  return line;
}

function updateStudyHeader() {
  const topic = selectedTopic();
  document.getElementById('study-topic-label').textContent = topic ? localized(topic.title) : '';
}

function normalizeForSearch(value) {
  return value.normalize('NFKC').toLocaleLowerCase(state.language === 'ja' ? 'ja' : 'vi');
}

function renderStudyList() {
  const container = document.getElementById('study-list');
  const query = normalizeForSearch(state.studyQuery.trim());
  const filtered = state.questions.filter((question) => {
    if (!query) return true;
    const searchable = [
      question.id,
      localized(question.question),
      localized(question.explanation),
      ...question.options.map(localized),
    ].join(' ');
    return normalizeForSearch(searchable).includes(query);
  });

  document.getElementById('study-result-count').textContent = t('studyCount', {
    shown: formatNumber(filtered.length),
    total: formatNumber(state.questions.length),
  });

  if (filtered.length === 0) {
    const message = document.createElement('p');
    message.className = 'empty-message';
    message.textContent = t('noSearchResults');
    container.replaceChildren(message);
    return;
  }

  const fragment = document.createDocumentFragment();
  filtered.forEach((question) => {
    const card = document.createElement('article');
    card.className = 'study-card';
    const meta = document.createElement('div');
    meta.className = 'study-meta';
    meta.append(makeTextSpan(question.id), makeTextSpan(question.source || ''));
    const heading = document.createElement('h3');
    heading.textContent = localized(question.question);
    const answers = document.createElement('div');
    answers.className = 'answer-summary';

    question.options.forEach((option) => {
      const line = makeAnswerLine(`${option.id}. ${localized(option)}`, option.id === question.correctOptionId ? 'correct-answer' : '');
      answers.append(line);
    });

    const label = document.createElement('span');
    label.className = 'study-answer-label';
    label.textContent = localized(question.explanation);
    card.append(meta, heading, answers, label);
    fragment.append(card);
  });
  container.replaceChildren(fragment);
}

function formatDuration(totalSeconds) {
  const safeSeconds = Math.max(0, Number(totalSeconds) || 0);
  const hours = Math.floor(safeSeconds / 3600);
  const minutes = Math.floor((safeSeconds % 3600) / 60);
  const seconds = safeSeconds % 60;
  return hours > 0
    ? `${String(hours).padStart(2, '0')}:${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`
    : `${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
}

function showScreen(screenId, scroll = true) {
  document.querySelectorAll('.screen').forEach((screen) => {
    screen.classList.toggle('active', screen.id === screenId);
  });
  state.currentScreen = screenId;
  if (scroll) window.scrollTo({ top: 0, behavior: 'smooth' });
}
